  function interpolateAnchors(anchors, level) {
    if (!anchors || !Number.isFinite(level) ||
        level < anchors[0][0] ||
        level > anchors[anchors.length - 1][0]) {
      return null;
    }
    const exact = anchors.find(anchor => anchor[0] === level);
    if (exact) {
      return exact[1];
    }
    const upperIndex = anchors.findIndex(anchor => anchor[0] > level);
    if (upperIndex <= 0) {
      return null;
    }
    const lower = anchors[upperIndex - 1];
    const upper = anchors[upperIndex];
    const fraction = (level - lower[0]) / (upper[0] - lower[0]);
    return Math.round(lower[1] + fraction * (upper[1] - lower[1]));
  }

  function legacyBasePrice(quality, level) {
    switch (quality) {
      case 4:
        return 10000 + 600 * level + Math.pow(0.16 * level, 2);
      case 3:
        return 500 + 525 * level;
      case 2:
        return 439 * level;
      default:
        return null;
    }
  }

  function sellPrice({
    itemClass,
    inventoryType,
    subclass,
    quality,
    level
  }) {
    if (![itemClass, inventoryType, subclass, quality, level].every(
      Number.isFinite
    )) {
      return null;
    }

    if (itemClass === 2 && quality === 2) {
      const anchors = UNCOMMON_WEAPON_ANCHORS[
        `${inventoryType}:${subclass}`
      ];
      const interpolated = interpolateAnchors(anchors, level);
      if (interpolated !== null) {
        return {
          copper: interpolated,
          source: 'AzerothCore uncommon random-enchantment weapon anchors'
        };
      }
    }

    if (itemClass === 4 && quality === 2) {
      const base = interpolateAnchors(UNCOMMON_ARMOR_BASE_ANCHORS, level);
      const slotMod = ARMOR_SLOT_MODS[inventoryType];
      const subclassMod = ARMOR_SUBCLASS_MODS[subclass];
      if (base !== null &&
          Number.isFinite(slotMod) &&
          Number.isFinite(subclassMod)) {
        return {
          copper: Math.floor(base * slotMod * subclassMod),
          source: (
            'monotone AzerothCore uncommon random-enchantment armor anchors'
          )
        };
      }
    }

    const base = legacyBasePrice(quality, level);
    if (base === null) {
      return null;
    }
    const slotMod = itemClass === 4
      ? ARMOR_SLOT_MODS[inventoryType]
      : LEGACY_WEAPON_SLOT_MODS[inventoryType];
    const subclassMod = itemClass === 4
      ? ARMOR_SUBCLASS_MODS[subclass]
      : 1;
    if (!Number.isFinite(slotMod) || !Number.isFinite(subclassMod)) {
      return null;
    }
    return {
      copper: Math.floor(base * slotMod * subclassMod),
      source: 'legacy quality/slot/subclass model'
    };
  }

  function denominations(totalCopper) {
    if (!Number.isFinite(totalCopper) || totalCopper < 0) {
      return null;
    }
    const copper = Math.floor(totalCopper);
    return {
      totalCopper: copper,
      gold: Math.floor(copper / 10000),
      silver: Math.floor(copper % 10000 / 100),
      copper: copper % 100
    };
  }

  function prices(input) {
    const sell = sellPrice(input);
    if (!sell) {
      return null;
    }
    const vendorMultiplier =
      input.itemClass === 4 &&
      [2, 11, 23].includes(input.inventoryType)
        ? 4
        : 5;
    return {
      source: sell.source,
      sell: denominations(sell.copper),
      buy: denominations(sell.copper * vendorMultiplier),
      vendorMultiplier
    };
  }

